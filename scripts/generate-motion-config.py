#!/usr/bin/env python3
"""Extract the BSD-licensed Bosch feature firmware from our pinned dependency."""
from pathlib import Path
import hashlib
import re

root = Path(__file__).resolve().parent.parent
source = root / "build/deps/InfiniTime/src/drivers/Bma421_C/bma423.c"
text = source.read_text()
destination = root / "internal/motionconfig"
destination.mkdir(exist_ok=True)
# Preserve the full upstream license alongside the extracted byte streams.
license_text = text[:text.index(" * @file")].replace("/**\n", "").replace(" * ", "").replace(" *\n", "\n")
(destination / "LICENSE").write_text(license_text.rstrip() + '\n')
output = ["// Code generated by scripts/generate-motion-config.py; DO NOT EDIT.\n",
          "// Bosch Sensortec feature firmware, BSD-3-Clause; see LICENSE.\n",
          "// Source: InfiniTime 6c119eb52206b580b556b41633dddc1e1b66a8da,\n",
          "// src/drivers/Bma421_C/bma423.c (Bosch V2.14.13).\n",
          "package motionconfig\n\n"]
for name in ("bma423", "bma425"):
    array = re.search(r"const uint8_t " + name + r"_config_file\[\] = \{(.*?)\};", text, re.S)[1]
    data = bytes(int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{2})", array))
    assert len(data) % 16 == 0
    output.append(f"// {len(data)} bytes; SHA256 {hashlib.sha256(data).hexdigest()}.\n")
    chunks = ['"' + ''.join(f"\\x{v:02x}" for v in data[i:i+32]) + '"' for i in range(0,len(data),32)]
    output.append(f"const {name.upper()} = " + " +\n\t".join(chunks) + "\n\n")
(destination / "config.go").write_text(''.join(output))
